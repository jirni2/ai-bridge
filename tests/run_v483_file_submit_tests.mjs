import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
const root=path.resolve(new URL("..",import.meta.url).pathname);
const html=fs.readFileSync(path.join(root,"index.html"),"utf8");
const app=fs.readFileSync(path.join(root,"app.js"),"utf8");
const css=fs.readFileSync(path.join(root,"styles.css"),"utf8");
assert.ok(html.includes('id="filePrompt"'),"Files tab must have a task textarea");
assert.ok(html.includes('id="fileSendBtn"'),"Files tab must have a visible send button");
assert.ok(html.includes('Надіслати файли + завдання'),"Files send CTA copy missing");
assert.ok(app.includes('$("fileSendBtn").onclick=()=>sendTask({source:"files"})'),"Files send button must submit through sendTask");
assert.ok(app.includes('const promptEl=source==="files"?$("filePrompt"):$("prompt")'),"sendTask must read the Files composer when invoked from Files");
assert.ok(app.includes('if(source==="files"&&!attachments.length)'),"Files submission must require an attachment");
assert.ok(/const context=source==="files"\?buildFileContext\((?:\{task:prompt\})?\):"";/.test(app),"Files context must be built only for explicit Files submissions");
assert.ok(app.includes('fileContext:context'),"Files must be submitted in a dedicated fileContext field instead of concatenated into the user task");
assert.ok(app.includes('if(source==="files")showPage("chat")'),"Files submission must reveal progress/result in Chat");
assert.ok(app.includes('fileBtn.disabled=v||!attachments.length||!($("filePrompt")?.value.trim())'),"Files send button must reflect busy/files/task state");
assert.ok(css.includes('.fileTaskCard'),"Files task composer styles missing");
console.log("v4.8.3 file-submit UI regression tests passed");
